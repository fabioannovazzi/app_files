"""Generate or check the common, hash-locked CPython 3.12 dependency graph."""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import subprocess
import tempfile
from pathlib import Path

__all__ = ["project_text", "main"]
ROOT = Path(__file__).resolve().parents[1]
PRODUCTS = ("vera", "clara", "lucia")
HEADER = "# Generated by scripts/lock_shared_runtime.py; CPython 3.12, all hosts.\n"


def project_text(root: Path) -> str:
    """Keep build inputs bound to the reviewed shared recipes and seed versions."""

    def lines(name: str) -> list[str]:
        return [
            line.strip()
            for line in (root / "plugins/vera" / name).read_text().splitlines()
            if line.strip() and not line.lstrip().startswith("#")
        ]

    return (
        '[project]\nname = "mparanza-shared-runtime"\nversion = "0.0.0"\n'
        'requires-python = "==3.12.*"\ndependencies = '
        + json.dumps(lines("requirements-shared-core.txt"), indent=2)
        + "\n[project.optional-dependencies]\nocr = "
        + json.dumps(lines("requirements-shared-ocr.txt"), indent=2)
        + "\n[tool.uv]\nconstraint-dependencies = "
        + json.dumps(lines("constraints-shared-macos-py312.txt"), indent=2)
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uv", default=shutil.which("uv"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.uv:
        parser.error("The build-time uv tool is required (reviewed version: 0.12.10).")
    project = ROOT / "scripts/shared-runtime"
    expected = project_text(ROOT)
    if args.check:
        if (project / "pyproject.toml").read_text() != expected:
            raise ValueError(
                "Shared lock inputs changed; regenerate and review the dependency lock."
            )
    else:
        (project / "pyproject.toml").write_text(expected)
        subprocess.run([args.uv, "lock", "--project", str(project)], check=True)
    with tempfile.TemporaryDirectory(prefix="shared-lock-") as temporary:
        for feature in ("core", "ocr"):
            output = Path(temporary) / f"{feature}.lock"
            command = [
                args.uv,
                "export",
                "--project",
                str(project),
                "--frozen",
                "--offline",
                "--no-dev",
                "--no-emit-project",
                "--no-header",
                "--quiet",
                "--cache-dir",
                str(Path(temporary) / "cache"),
                "--output-file",
                str(output),
            ]
            if feature == "ocr":
                command.extend(["--extra", "ocr"])
            subprocess.run(command, check=True)
            content = HEADER + output.read_text()
            for product in PRODUCTS:
                path = (
                    ROOT / "plugins" / product / f"requirements-shared-{feature}.lock"
                )
                if args.check:
                    if path.read_text() != content:
                        raise ValueError(f"Stale shared dependency lock: {path}")
                else:
                    path.write_text(content)
    logging.info("All three products have the same exported dependency locks.")
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    raise SystemExit(main())
