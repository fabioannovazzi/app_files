def candidate_id(candidate: AmountCandidate) -> str:
    content = "|".join(
        (
            candidate.source_artifact_ref,
            candidate.location,
            candidate.token,
            decimal_text(candidate.amount),
        )
    )
    return "candidate." + hashlib.sha256(content.encode("utf-8")).hexdigest()


